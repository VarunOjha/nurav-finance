"""Wealth projection engine: a pure function over a JSON-shaped plan.

The only engine: the Wealth Agent never computes numbers, it drafts a plan
that this runs. Checked against golden vectors (tests/data/engine_golden.json,
regenerated by scripts/engine_golden.py after a deliberate change).

Rules:
- Plan year y = 1..H. A bucket's balance at year 0 is its starting value.
- Rates are effective annual: per period (n = 12, 4 or 1 a year) the rate is
  (1 + r)^(1/n) - 1, so compounding only changes contribution timing.
- Monthly contributions are credited at the end of each month; with quarterly
  or annual compounding they collect without interest and land at the end of
  the period (annual = 12 x amount at year end).
- Yearly contributions and one-offs land at the end of the plan year, after
  that year's growth.
- Step-up: amount x (1 + s)^(years since the phase started).
- Phases run back to back; every phase but the last lasts `years`, the last
  runs to the end of the horizon.
- Withdrawals never take a bucket below 0: the rest is skipped and the bucket's
  `depleted_year` records the first year that happened.
- Inflation: target(t) = target_today x (1 + i)^t, real(t) = nominal(t) / (1 + i)^t.
  With `target_fixed` the target is a fixed nominal amount instead (no growth).
- `flat_rate` (optional) replaces every phase's rate; `extra` ({bucket,
  monthly}, optional) adds a flat monthly amount to one bucket. Both describe
  a solved plan (required return / required savings) so it can be drawn.
- FI: the first period end where the total reaches the target, in months.
- Required return: one flat rate replacing every phase's rate (bisection,
  -20%..50%). Required contribution: extra per month into one bucket (the
  largest at the start unless chosen). Both aim at the target at the horizon.

Floats, not Decimal: these are projections, not ledger amounts.
"""

from typing import Any

RATE_LO, RATE_HI = -20.0, 50.0
ITERATIONS = 60


def _spans(phases: list[dict], horizon: int) -> list[tuple[int, int, dict]]:
    out = []
    start = 1
    for i, p in enumerate(phases):
        n = horizon - start + 1 if i == len(phases) - 1 else int(p["years"])
        out.append((start, start + n - 1, p))
        start += n
    return out


def _phase_at(spans: list[tuple[int, int, dict]], year: int) -> tuple[int, dict]:
    for start, end, p in spans:
        if start <= year <= end:
            return start, p
    return spans[-1][0], spans[-1][2]


def _target_at(plan: dict, t: float) -> float:
    growth = 0.0 if plan.get("target_fixed") else plan["inflation"] / 100
    return plan["target_today"] * (1 + growth) ** t


def _simulate(plan: dict, flat_rate: float | None = None, extra_key: str | None = None, extra: float = 0.0) -> dict:
    if flat_rate is None:
        flat_rate = plan.get("flat_rate")
    if extra_key is None and plan.get("extra"):
        extra_key, extra = plan["extra"]["bucket"], float(plan["extra"]["monthly"])
    horizon = int(plan["horizon_years"])
    n = int(plan["compounding"])
    target = plan.get("target_today")
    buckets = plan["buckets"]
    spans = [_spans(b["phases"], horizon) for b in buckets]

    bal = [float(b["start"]) for b in buckets]
    values = [[v] for v in bal]
    added = [[0.0] for _ in buckets]
    # `added` split by source: regular contributions/withdrawals and one-offs (added = regular + one_off).
    regular = [[0.0] for _ in buckets]
    one_off = [[0.0] for _ in buckets]
    depleted: list[int | None] = [None] * len(buckets)
    fi = 0 if target is not None and sum(bal) >= target else None

    def credit(i: int, amount: float, year: int) -> float:
        if bal[i] + amount < 0:
            applied = -bal[i]
            bal[i] = 0.0
            if depleted[i] is None:
                depleted[i] = year
            return applied
        bal[i] += amount
        return amount

    for year in range(1, horizon + 1):
        rate_per = []
        monthly = []
        yearly = []
        for i, b in enumerate(buckets):
            start, p = _phase_at(spans[i], year)
            rate = p["rate"] if flat_rate is None else flat_rate
            rate_per.append((1 + rate / 100) ** (1 / n) - 1)
            amount = p["amount"] * (1 + p["step_up"] / 100) ** (year - start)
            monthly.append((amount if p["per"] == "month" else 0.0) + (extra if b["key"] == extra_key else 0.0))
            yearly.append(amount if p["per"] == "year" else 0.0)
        year_regular = [0.0] * len(buckets)
        year_one_off = [0.0] * len(buckets)
        for k in range(1, n + 1):
            for i in range(len(buckets)):
                bal[i] = bal[i] * (1 + rate_per[i])
                if monthly[i]:
                    year_regular[i] += credit(i, monthly[i] * 12 / n, year)
                if k == n:
                    if yearly[i]:
                        year_regular[i] += credit(i, yearly[i], year)
                    for o in buckets[i]["one_offs"]:
                        if int(o["year"]) == year and o["amount"]:
                            year_one_off[i] += credit(i, o["amount"], year)
            if fi is None and target is not None and sum(bal) >= _target_at(plan, (year - 1) + k / n):
                fi = (year - 1) * n + k
        for i in range(len(buckets)):
            values[i].append(bal[i])
            added[i].append(year_regular[i] + year_one_off[i])
            regular[i].append(year_regular[i])
            one_off[i].append(year_one_off[i])

    return {"values": values, "added": added, "regular": regular, "one_off": one_off, "depleted": depleted, "fi_period": fi}


def _end_total(plan: dict, **kw: Any) -> float:
    return sum(v[-1] for v in _simulate(plan, **kw)["values"])


def _bisect(f, lo: float, hi: float) -> float:
    for _ in range(ITERATIONS):
        mid = (lo + hi) / 2
        if f(mid) >= 0:
            hi = mid
        else:
            lo = mid
    return hi


def _base(plan: dict) -> dict:
    """The plan without a solved flat rate or extra: what the solves start from."""
    return {k: v for k, v in plan.items() if k not in ("flat_rate", "extra")}


def required_rate(plan: dict, target_end: float) -> dict:
    plan = _base(plan)

    def f(r: float) -> float:
        return _end_total(plan, flat_rate=r) - target_end

    if f(RATE_LO) >= 0:
        return {"status": "already", "value": RATE_LO}
    if f(RATE_HI) < 0:
        return {"status": "unreachable", "value": None}
    return {"status": "ok", "value": _bisect(f, RATE_LO, RATE_HI)}


def contribution_bucket(plan: dict) -> str:
    keys = [b["key"] for b in plan["buckets"]]
    chosen = plan.get("contrib_bucket")
    if chosen in keys:
        return chosen
    best = max(plan["buckets"], key=lambda b: b["start"])  # first of equals wins
    return best["key"]


def required_contribution(plan: dict, target_end: float) -> dict:
    plan = _base(plan)
    key = contribution_bucket(plan)

    def f(e: float) -> float:
        return _end_total(plan, extra_key=key, extra=e) - target_end

    if f(0.0) >= 0:
        return {"status": "already", "value": 0.0, "bucket": key}
    hi = 1000.0
    while f(hi) < 0:
        hi *= 2
        if hi > 1e12:
            return {"status": "unreachable", "value": None, "bucket": key}
    return {"status": "ok", "value": _bisect(f, 0.0, hi), "bucket": key}


def project(plan: dict, solve: bool = True) -> dict:
    """Run a plan. `plan` keys: horizon_years, compounding (12|4|1), inflation (%),
    target_today (or None), target_fixed (optional), contrib_bucket (or None),
    flat_rate / extra (optional), buckets: [{key, start, phases: [{years, rate,
    amount, per: 'month'|'year', step_up}], one_offs: [{year, amount}]}].
    `solve=False` skips the required-rate / required-contribution searches."""
    horizon = int(plan["horizon_years"])
    n = int(plan["compounding"])
    infl = plan["inflation"] / 100
    sim = _simulate(plan)
    total = [sum(v[y] for v in sim["values"]) for y in range(horizon + 1)]
    target_today = plan.get("target_today")
    target = None if target_today is None else [_target_at(plan, y) for y in range(horizon + 1)]
    fi = sim["fi_period"]
    return {
        "horizon_years": horizon,
        "buckets": [
            {
                "key": b["key"],
                "values": sim["values"][i],
                "added": sim["added"][i],
                "regular": sim["regular"][i],
                "one_off": sim["one_off"][i],
                "depleted_year": sim["depleted"][i],
            }
            for i, b in enumerate(plan["buckets"])
        ],
        "total": total,
        "total_real": [t / (1 + infl) ** y for y, t in enumerate(total)],
        "target": target,
        "fi_months": None if fi is None else round(fi * 12 / n),
        "required_rate": None if target is None or not solve else required_rate(plan, target[-1]),
        "required_contribution": None if target is None or not solve else required_contribution(plan, target[-1]),
    }
